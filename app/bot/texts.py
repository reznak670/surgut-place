def frost_mode() -> bool:
    raw = getattr(settings, "FROST_MODE", False)
    if isinstance(raw, str):
        return raw.strip().lower() in ("1", "true", "yes", "on")
    return bool(raw)


def season(d: date) -> str:
    """Сезон по дате (без учёта FROST_MODE)."""
    m, day = d.month, d.day
    if m in (12, 1, 2):
        return "deep_winter"
    if m in (11, 3):
        return "winter"
    if m == 4 or (m == 5 and day <= 24):
        return "thaw"
    if (m == 5 and day >= 25) or m == 6 or (m == 7 and day <= 15):
        return "white_nights"
    if m in (7, 8):
        return "summer"
    return "autumn"


def seasonal(key: str, d: date, *, frost: bool | None = None) -> str:
    """Сезонный вариант текста; `frost` перекрывает сезон, если для ключа есть вариант."""
    variants = SEASONS[key]
    if (frost_mode() if frost is None else frost) and "frost" in variants:
        return variants["frost"]
    return variants.get(season(d)) or variants["default"]


