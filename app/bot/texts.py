_ANCHOR_RE = re.compile(r'<a href="\{privacy_url\}">(.*?)</a>')


def with_privacy(template: str, privacy_url: str, **kwargs: object) -> str:
    """Подставляет ссылку на политику ПД. Если URL не задан — оставляет просто текст
    (пустой href Telegram не примет)."""
    if not privacy_url:
        template = _ANCHOR_RE.sub(r"\1", template)
        return template.format(**kwargs)
    from html import escape

    return template.format(privacy_url=escape(privacy_url, quote=True), **kwargs)
